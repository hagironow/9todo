// Widen literal types so en.ts can provide different string values
type DeepWiden<T> = T extends readonly (infer U)[]
  ? U extends string ? string[] : DeepWiden<U>[]
  : T extends (...args: infer A) => infer R
  ? (...args: A) => R extends string ? string : R
  : T extends object
  ? { [K in keyof T]: DeepWiden<T[K]> }
  : T extends string ? string : T;

export type Translations = DeepWiden<typeof ko>;
